#!/usr/bin/env python3
"""Write variants/bitchat/platformio.ini: one bridge environment per stock ESP32 Bluetooth companion.

Run after merging upstream changes, with PlatformIO installed:  python tools/bitchat/generate_envs.py
"""

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "variants/bitchat/platformio.ini"
SUFFIX = "_bitchat"

HEADER = """; Generated by tools/bitchat/generate_envs.py; do not edit by hand.
;
; Companion firmware with the Bitchat bridge. Each environment extends a stock Bluetooth companion and
; swaps its Bluetooth interface for one on the NimBLE stack, shared with the bridge.

[bitchat_bridge_esp32]
build_unflags =
  -std=gnu++11
build_flags =
  -std=gnu++17
  -D WITH_BITCHAT_BRIDGE=1
  -D FIRMWARE_VERSION='"v1.18.0-bitchat1.2.1"'
  -D ARDUINO_LOOP_STACK_SIZE=16384
  -D CONFIG_BT_NIMBLE_ENABLED
  -D CONFIG_BT_NIMBLE_MAX_BONDS=6
  -D CONFIG_BT_NIMBLE_MAX_CCCDS=20
  -D CONFIG_BT_NIMBLE_HOST_TASK_STACK_SIZE=8192
  -D CONFIG_NIMBLE_CPP_LOG_LEVEL=0
  -D MYNEWT_VAL_BLE_HS_LOG_LVL=LOG_LEVEL_CRITICAL
build_src_filter =
  -<helpers/esp32/SerialBLEInterface.cpp>
  +<helpers/bitchat/*.cpp>
  +<helpers/bitchat/esp32/*.cpp>
lib_deps =
  h2zero/NimBLE-Arduino@1.4.3
; the framework's own Bluetooth library is the other stack; only one can be linked
lib_ignore =
  BLE
extra_scripts =
  pre:tools/bitchat/nimble_pre.py
"""

BLOCK = """
[env:{name}]
extends = env:{stock}
build_unflags =
  ${{env:{stock}.build_unflags}}
  ${{bitchat_bridge_esp32.build_unflags}}
build_flags =
  ${{env:{stock}.build_flags}}
  ${{bitchat_bridge_esp32.build_flags}}
build_src_filter =
  ${{env:{stock}.build_src_filter}}
  ${{bitchat_bridge_esp32.build_src_filter}}
lib_deps =
  ${{env:{stock}.lib_deps}}
  ${{bitchat_bridge_esp32.lib_deps}}
lib_ignore =
  ${{env:{stock}.lib_ignore}}
  ${{bitchat_bridge_esp32.lib_ignore}}
extra_scripts =
  ${{env:{stock}.extra_scripts}}
  ${{bitchat_bridge_esp32.extra_scripts}}
"""


# nRF52: experimental, one board at a time. The SoftDevice gets 40 KB of RAM instead of 24 KB for the
# second link and the larger attribute table; the value is an estimate, not a measurement.
NRF52 = """
[bitchat_bridge_nrf52]
build_unflags =
  -std=gnu++11
build_flags =
  -std=gnu++17
  -I src/helpers/bitchat/nrf52/shim
  -D WITH_BITCHAT_BRIDGE=1
  -D FIRMWARE_VERSION='"v1.18.0-bitchat1.2.1"'
  ; fewer messages kept for an absent app: that memory goes to the bridge and the Bluetooth stack
  -D OFFLINE_QUEUE_SIZE=96
  ; a shorter public history: this chip has less memory
  -D BITCHAT_HISTORY_ENTRIES=8
build_src_filter =
  -<helpers/nrf52/SerialBLEInterface.cpp>
  +<helpers/bitchat/*.cpp>
  +<helpers/bitchat/nrf52/*.cpp>
extra_scripts =
  pre:tools/bitchat/nimble_pre.py
"""


# nRF52 companions with the bridge: the popular boards, each with the linker script of its SoftDevice, its RAM
# start moved up for the larger Bluetooth tables of the bridge (two links, two services).
NRF52_BOARDS = [
    ("t1000e_companion_radio_ble", "nrf52840_s140_v7_extrafs_bridge.ld"),
    ("RAK_4631_companion_radio_ble", "nrf52840_s140_v6_extrafs_bridge.ld"),
    ("LilyGo_T-Echo_companion_radio_ble", "nrf52840_s140_v6_extrafs_bridge.ld"),
    ("Heltec_t114_companion_radio_ble", "nrf52840_s140_v6_extrafs_bridge.ld"),
    ("Heltec_t114_without_display_companion_radio_ble", "nrf52840_s140_v6_extrafs_bridge.ld"),
    ("ThinkNode_M1_companion_radio_ble", "nrf52840_s140_v6_extrafs_bridge.ld"),
    ("Xiao_nrf52_companion_radio_ble", "nrf52840_s140_v7_extrafs_bridge.ld"),
]

NRF52_BLOCK = """
[env:{name}]
extends = env:{stock}
board_build.ldscript = variants/bitchat/{ld}
build_unflags = ${{bitchat_bridge_nrf52.build_unflags}}
build_flags =
  ${{env:{stock}.build_flags}}
  ${{bitchat_bridge_nrf52.build_flags}}
build_src_filter =
  ${{env:{stock}.build_src_filter}}
  ${{bitchat_bridge_nrf52.build_src_filter}}
extra_scripts =
  ${{env:{stock}.extra_scripts}}
  ${{bitchat_bridge_nrf52.extra_scripts}}
"""


def text(value):
    return " ".join(value) if isinstance(value, list) else str(value or "")


def stock_environments():
    raw = subprocess.run(
        ["pio", "project", "config", "--json-output"], cwd=ROOT, check=True, capture_output=True, text=True
    )
    found = []
    for section, options in json.loads(raw.stdout):
        options = dict(options)
        if not section.startswith("env:") or section.endswith(SUFFIX):
            continue
        flags, sources = text(options.get("build_flags")), text(options.get("build_src_filter"))
        # The NimBLE library pinned here does not build on the newer framework the ESP32-C6 boards use.
        if (
            "ESP32_PLATFORM" in flags
            and "BLE_PIN_CODE" in flags
            and "companion_radio" in sources
            and text(options.get("platform")).startswith("platformio/espressif32")
        ):
            found.append(section[4:])
    return sorted(found, key=str.lower)


def main():
    # The generated file must not feed its own input.
    TARGET.write_text(HEADER)
    stock = stock_environments()
    nrf52 = "".join(NRF52_BLOCK.format(name=name + SUFFIX, stock=name, ld=ld) for name, ld in NRF52_BOARDS)
    TARGET.write_text(
        HEADER + "".join(BLOCK.format(name=name.rstrip("_") + SUFFIX, stock=name) for name in stock) + NRF52 + nrf52
    )
    print(f"{len(stock)} bridge environments written to {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
